/**
 * Build `lib/client.js` — the `__ModuleLoader__` bundle the Web GUI serves.
 *
 * `src/client.js` is a single default-export factory; this script wraps it
 * verbatim into the classic-script factory the page's module table loads. No
 * bundler is used or needed. The build refuses to run if the source grows a
 * second export, because the transform is deliberately a single replacement.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const PKG_ID = 'dsh-plugin-balance'

const source = readFileSync(join(here, 'src', 'client.js'), 'utf8')

const exportLines = source.split('\n').filter(function (line) { return /^export\s/.test(line) })
if (exportLines.length !== 1) {
  throw new Error('build: src/client.js must have exactly one export (the default factory); found ' + exportLines.length)
}
if (!/^export default function createClient\b/.test(exportLines[0])) {
  throw new Error('build: the single export must be `export default function createClient(env)`; found: ' + exportLines[0])
}

const body = source.replace(/^export default function createClient/m, 'function createClient')

const bundle = `// @generated by build.mjs from src/client.js — do not edit by hand.
// Classic script: registers a CommonJS factory with the page's module loader.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(PKG_ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;

${body}

		const plugin = createClient({ React: require("react") });
		exports.apply = plugin.apply;
		exports.inject = plugin.inject;
		return module.exports;
	}
});
`

mkdirSync(join(here, 'lib'), { recursive: true })
writeFileSync(join(here, 'lib', 'client.js'), bundle)
console.log('build: wrote lib/client.js (' + Buffer.byteLength(bundle) + ' bytes)')
