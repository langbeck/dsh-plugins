/**
 * Build `lib/client.js` — the `__ModuleLoader__` bundle the Web GUI serves.
 *
 * `src/client/index.jsx` is a single default-export factory. esbuild bundles it
 * to CommonJS with React and the JSX runtime left external; this script wraps
 * that output in the classic-script factory the page's module table loads. The
 * wrapper keeps the Host's `require` available, so the bundle's React imports
 * resolve from the page's shared module table at materialization time.
 */

import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const here = dirname(fileURLToPath(import.meta.url))
const PKG_ID = 'dsh-plugin-session-settings'

const result = await build({
  entryPoints: [join(here, 'src', 'client', 'index.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  logLevel: 'silent',
})

if (result.outputFiles.length !== 1) {
  throw new Error(`build: expected one client output, got ${result.outputFiles.length}`)
}
const clientCode = result.outputFiles[0].text

const bundle = `// @generated by build.mjs from src/client/index.jsx — do not edit by hand.
// Classic script: registers a CommonJS factory with the page's module loader.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(PKG_ID)},
	factory: (require) => {
		var module = { exports: {} };

${clientCode}

		const plugin = module.exports.default();
		module.exports = { apply: plugin.apply, inject: plugin.inject };
		return module.exports;
	}
});
`

// Validate the generated wrapper before writing it: one registered factory,
// a default createClient, and the expected exports.
let entry
const sandbox = { window: { __ModuleLoader__: { load(definition) { entry = definition } } } }
vm.runInNewContext(bundle, sandbox, { filename: 'lib/client.js' })
if (entry === undefined || entry.id !== PKG_ID) throw new Error('build: the bundle did not register its module id')
const react = {
  createElement() { return null },
  useState(value) { return [typeof value === 'function' ? value() : value, () => {}] },
  useEffect() {},
  useRef(value) { return { current: value } },
}
const jsxRuntime = { jsx() { return null }, jsxs() { return null }, Fragment: 'Fragment' }
const plugin = entry.factory((specifier) => {
  if (specifier === 'react') return react
  if (specifier === 'react/jsx-runtime') return jsxRuntime
  throw new Error('unexpected require: ' + specifier)
})
if (typeof plugin.apply !== 'function' || !Array.isArray(plugin.inject)) {
  throw new Error('build: generated bundle does not export apply/inject')
}

mkdirSync(join(here, 'lib'), { recursive: true })
writeFileSync(join(here, 'lib', 'client.js'), bundle)
console.log('build: wrote lib/client.js (' + Buffer.byteLength(bundle) + ' bytes)')
